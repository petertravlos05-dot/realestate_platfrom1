// Αφαίρεση διπλοτύπων και ταξινόμηση
const unique = [...new Set(GREEK_LOCATIONS.map((s) => s.trim()).filter(Boolean))].sort((a, b) =>
  a.localeCompare(b, 'el')
);

function searchInList(list: string[], query: string, limit: number): string[] {
  const q = query
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
  if (!q.trim()) return [];
  return list
    .filter((loc) => {
      const normalized = loc
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '');
      return normalized.includes(q) || q.split(/\s+/).every((w) => normalized.includes(w));
    })
    .slice(0, limit);
}

export function searchGreekPrefectures(query: string, limit = 10): string[] {
  return searchInList(GREEK_PREFECTURES, query, limit);
}

export function searchGreekLocations(query: string, limit = 10): string[] {
  return searchInList(unique, query, limit);
}
